# Binary & Include File Generators
# -----------------------------------------------------------------------------
def build_font_bins(build_dir):
    os.makedirs(build_dir, exist_ok=True)
    f5_path    = os.path.join(build_dir, "font5.bin")
    f6_path    = os.path.join(build_dir, "font6.bin")
    fvw_path   = os.path.join(build_dir, "fontvw.bin")
    fvw_inc    = os.path.join(build_dir, "fontvw.inc")
    fvw_wpath  = os.path.join(build_dir, "fontvw_widths.bin")
    
    # Character export list: ASCII 32..126 + extras \x80..\x86
    chars_to_export = [chr(i) for i in range(32, 127)] + ['\x80', '\x81', '\x82', '\x83', '\x84', '\x85', '\x86']
    
    data5  = bytearray()
    data6  = bytearray()
    datavw = bytearray()
    widths = bytearray()
    inc_lines = [
        "; fontvw.inc -- variable-width font advance widths in pixels (EarthBound style)",
        "; Generated automatically by tools/fontmock.py -- do not edit.",
        f"; Total glyphs: {len(chars_to_export)} (ASCII 32..126 + UI extras 128..134)",
        "; Advance = glyph real ink width + 1 px spacing (space = 3 px).",
        "fontvw_widths:"
    ]
    
    for ch in chars_to_export:
        r5  = GLYPHS_5.get(ch, ["...."]*8)
        r6  = GLYPHS_6.get(ch, ["....."]*8)
        rvw = GLYPHS_VW.get(ch, ["........"]*8)
        adv = PROSE_WIDTHS.get(ch, 4)
        widths.append(adv)
        
        ch_desc = ch if (32 <= ord(ch) <= 126 and ch not in "\\'") else f"0x{ord(ch):02X}"
        inc_lines.append(f"    .DB {adv:<2}  ; '{ch_desc}' (ink {PROSE_INK_WIDTHS.get(ch, 0)} px)")
        
        # 1 bpp: MSB = leftmost pixel (bit 7)
        for row in r5:
            b = 0
            for i, p in enumerate(row):
                if p == '#': b |= (0x80 >> i)
            data5.append(b)
            
        for row in r6:
            b = 0
            for i, p in enumerate(row):
                if p == '#': b |= (0x80 >> i)
            data6.append(b)
            
        for row in rvw:
            b = 0
            for i, p in enumerate(row):
                if p == '#': b |= (0x80 >> i)
            datavw.append(b)
            
    with open(f5_path, "wb") as f:
        f.write(data5)
    with open(f6_path, "wb") as f:
        f.write(data6)
    with open(fvw_path, "wb") as f:
        f.write(datavw)
    with open(fvw_wpath, "wb") as f:
        f.write(widths)
    with open(fvw_inc, "w", encoding="utf-8") as f:
        f.write("\n".join(inc_lines) + "\n")
        
    print(f"Exported {f5_path} ({len(data5)} bytes, {len(chars_to_export)} glyphs)")
    print(f"Exported {f6_path} ({len(data6)} bytes, {len(chars_to_export)} glyphs)")
    print(f"Exported {fvw_path} ({len(datavw)} bytes, {len(chars_to_export)} glyphs)")
    print(f"Exported {fvw_wpath} ({len(widths)} bytes)")
    print(f"Exported {fvw_inc} ({len(chars_to_export)} entries)")

