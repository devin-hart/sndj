def render_text_fixed(img, text, x0, y0, font_dict, cell_w, color, bg_color=None):
    draw = ImageDraw.Draw(img)
    cur_x = x0
    for ch in text:
        r = font_dict.get(ch, font_dict[' '])
        if bg_color and 0 <= cur_x < img.width and 0 <= y0 < img.height:
            draw.rectangle([cur_x, y0, min(img.width - 1, cur_x + cell_w - 1), min(img.height - 1, y0 + 7)], fill=bg_color)
        for y, row in enumerate(r):
            py = y0 + y
            if 0 <= py < img.height:
                for x, bit in enumerate(row):
                    px = cur_x + x
                    if bit == '#' and 0 <= px < img.width:
                        img.putpixel((px, py), color)
        cur_x += cell_w

def render_text_prose(img, text, x0, y0, color, bg_color=None):
    draw = ImageDraw.Draw(img)
    cur_x = x0
    for ch in text:
        r = GLYPHS_VW.get(ch, GLYPHS_VW[' '])
        adv = PROSE_WIDTHS.get(ch, 4)
        if bg_color and 0 <= cur_x < img.width and 0 <= y0 < img.height:
            draw.rectangle([cur_x, y0, min(img.width - 1, cur_x + adv - 1), min(img.height - 1, y0 + 7)], fill=bg_color)
        for y, row in enumerate(r):
            py = y0 + y
            if 0 <= py < img.height:
                for x, bit in enumerate(row):
                    px = cur_x + x
                    if bit == '#' and 0 <= px < img.width:
                        img.putpixel((px, py), color)
        cur_x += adv

