# -----------------------------------------------------------------------------
# Metric Normalization for Variable-Width Font
# -----------------------------------------------------------------------------
GLYPHS_VW = {}
PROSE_WIDTHS = {}
PROSE_INK_WIDTHS = {}

for ch, raw_rows in GLYPHS_VW_RAW.items():
    min_c = 8
    max_c = -1
    for r in raw_rows:
        for c, bit in enumerate(r):
            if bit == '#':
                if c < min_c: min_c = c
                if c > max_c: max_c = c
    if max_c == -1: # empty / space
        GLYPHS_VW[ch] = ["........"] * 8
        PROSE_INK_WIDTHS[ch] = 0
        PROSE_WIDTHS[ch] = 3 # 3 px advance for space
    else:
        ink_w = max_c - min_c + 1
        # Left-align so min_c becomes column 0 (bit 7)
        norm_rows = []
        for r in raw_rows:
            ink = r[min_c : min_c + ink_w]
            norm_rows.append(ink.ljust(8, '.'))
        GLYPHS_VW[ch] = norm_rows
        PROSE_INK_WIDTHS[ch] = ink_w
        # Mathematical advance: real ink width + 1 pixel gap
        PROSE_WIDTHS[ch] = ink_w + 1

