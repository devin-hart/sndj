#!/usr/bin/env python3
"""tools/makecmdhelp.py — generate build/cmdhelp.inc from tools/commands.csv
Outputs:
  cmdhelp_ptrs: table of 16-bit pointers for commands 0..26 (0 = none, 1 = A .. 26 = Z)
  str_cmdhelp_N: null-terminated strings for each command
"""
import csv
import sys
import os

def main():
    if len(sys.argv) < 3:
        src = "tools/commands.csv"
        dst = "build/cmdhelp.inc"
    else:
        src = sys.argv[1]
        dst = sys.argv[2]

    cmds = {}
    with open(src, "r", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            letter = row["letter"].strip().upper()
            short = row["short"].strip()
            assert len(short) <= 22, f"Command {letter} short text too long ({len(short)} > 22): {short}"
            cmds[letter] = short

    lines = []
    lines.append("; Generated by tools/makecmdhelp.py from tools/commands.csv — do not edit\n")
    lines.append("cmdhelp_ptrs:")
    for i in range(27):
        if i == 0:
            lines.append(f"    .DW str_cmdhelp_{i}         ; 0 (none)")
        else:
            letter = chr(ord('A') + i - 1)
            lines.append(f"    .DW str_cmdhelp_{i}         ; {i} ({letter})")

    lines.append("\nstr_cmdhelp_0: .DB 0")
    for i in range(1, 27):
        letter = chr(ord('A') + i - 1)
        text = cmds.get(letter, "")
        if text:
            # Escape double quotes if any
            escaped = text.replace('"', '\\"')
            lines.append(f'str_cmdhelp_{i}: .DB "{escaped}", 0')
        else:
            lines.append(f"str_cmdhelp_{i}: .DB 0")

    lines.append("")

    out_dir = os.path.dirname(dst)
    if out_dir and not os.path.exists(out_dir):
        os.makedirs(out_dir, exist_ok=True)

    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))

    print(f"makecmdhelp: {len(cmds)} commands -> {dst}")

if __name__ == "__main__":
    main()
